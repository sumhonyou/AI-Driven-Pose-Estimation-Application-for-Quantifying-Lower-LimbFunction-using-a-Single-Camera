"""SLS evaluation harness: replays the committed corpus through the deterministic
analysis core and reports measurement AGREEMENT (not classifier accuracy) between
the system's hold time / band and the corpus's simulated manual (human-timed)
reference -- per the blueprint's evaluation framing note.

Reads only committed data (backend/app/module_a/replay_corpus/sls/), so this is
reproducible without a live session or database. Re-generate the corpus with
`generate_sls_replay_corpus.py` if you want to change the samples; this script
never mutates it.

Usage:
    python -m app.module_a.scripts.run_sls_evaluation
    python -m app.module_a.scripts.run_sls_evaluation --report-out FILE.md
"""

import argparse
import json
from pathlib import Path

from app.module_a import config
from app.module_a.evaluation.agreement import bland_altman, cohens_kappa, icc_2_1
from app.module_a.sls import analysis
from app.module_a.sls.scoring import hold_time_band

CORPUS_DIR = Path(__file__).resolve().parents[1] / "replay_corpus" / "sls"
DEFAULT_REPORT_PATH = (
    Path(__file__).resolve().parents[1] / "evaluation" / "SLS_EVALUATION_REPORT.md"
)


def load_corpus() -> list[dict]:
    labels_path = CORPUS_DIR / "labels.json"
    if not labels_path.exists():
        raise FileNotFoundError(
            f"No corpus at {CORPUS_DIR} -- run "
            "`python -m app.module_a.scripts.generate_sls_replay_corpus` first."
        )
    return json.loads(labels_path.read_text())


def evaluate() -> dict:
    manifest = load_corpus()
    rows = []
    for entry in manifest:
        frames = json.loads((CORPUS_DIR / entry["frames_file"]).read_text())
        result = analysis.analyze_leg(frames, entry["leg"])["metrics"]
        rows.append(
            {
                "sample_id": entry["sample_id"],
                "leg": entry["leg"],
                "system_hold_sec": result["holdSeconds"],
                "manual_hold_sec": entry["manual_hold_sec"],
                "system_band": hold_time_band(result["holdSeconds"]),
                "manual_band": hold_time_band(entry["manual_hold_sec"]),
                "system_stop_reason": result["stopReason"],
            }
        )

    system_holds = [r["system_hold_sec"] for r in rows]
    manual_holds = [r["manual_hold_sec"] for r in rows]
    system_bands = [r["system_band"] for r in rows]
    manual_bands = [r["manual_band"] for r in rows]

    return {
        "rows": rows,
        "icc_2_1": round(icc_2_1(system_holds, manual_holds), 4),
        "bland_altman": bland_altman(system_holds, manual_holds),
        "cohens_kappa": round(cohens_kappa(system_bands, manual_bands), 4),
        "n": len(rows),
    }


def render_report(result: dict) -> str:
    ba = result["bland_altman"]
    lines = [
        "# SLS Measurement-Agreement Evaluation",
        "",
        "Auto-generated by `app.module_a.scripts.run_sls_evaluation` from the committed",
        "replay corpus (`app/module_a/replay_corpus/sls/`). Re-run the script to regenerate.",
        "",
        "## Framing",
        "",
        "This is a **measurement-agreement** evaluation (system hold-time vs a simulated",
        "human-timed reference), not classifier accuracy -- consistent with the project's",
        "non-diagnostic, functional-self-check framing. Band agreement (Cohen's kappa) is",
        "computed on the **hold-time band only** (Poor/Fair/Good/Invalid from raw seconds),",
        "since a human reviewing video with a stopwatch can reproduce that dimension but",
        "can't independently judge the ball-in-circle stability sub-score the way the system",
        "does; the stability sub-score would need a separate rater protocol (future work).",
        "",
        f"Corpus: {result['n']} synthetic per-leg samples spanning Poor/Fair/Good/Invalid,",
        "steady and swaying variants (`generate_sls_replay_corpus.py`, fixed seed -- no real",
        "pilot recordings exist yet for this prototype).",
        "",
        "## Aggregate results",
        "",
        f"- **ICC(2,1)** (absolute agreement, hold time): `{result['icc_2_1']}`",
        f"- **Bland-Altman bias** (system - manual): `{ba['bias_sec']}s`",
        f"- **Bland-Altman 95% limits of agreement**: `[{ba['loa_lower_sec']}s, {ba['loa_upper_sec']}s]`",
        f"- **Cohen's kappa** (hold-time band agreement): `{result['cohens_kappa']}`",
        "",
        "## Per-sample detail",
        "",
        "| sample | leg | system hold (s) | manual hold (s) | system band | manual band | stop reason |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in result["rows"]:
        lines.append(
            f"| {r['sample_id']} | {r['leg']} | {r['system_hold_sec']:.2f} | "
            f"{r['manual_hold_sec']:.2f} | {r['system_band']} | {r['manual_band']} | "
            f"{r['system_stop_reason']} |"
        )

    mismatches = [r for r in result["rows"] if r["system_band"] != r["manual_band"]]
    lines.append("")
    if mismatches:
        lines.append(
            "**Band disagreements** (the only samples pulling kappa below 1.0):"
        )
        lines.append("")
        for r in mismatches:
            lines.append(
                f"- `{r['sample_id']}`: system=`{r['system_band']}` "
                f"({r['system_hold_sec']:.2f}s) vs manual=`{r['manual_band']}` "
                f"({r['manual_hold_sec']:.2f}s). The system reports `invalid` when the lift-line "
                "was never validly crossed, while a naive time-based reference labeller may still "
                "clock a small positive duration and call it `poor` -- a genuine edge-case "
                "divergence between the two measurement approaches, not a scoring bug."
            )
    else:
        lines.append("No band disagreements in this corpus.")

    lines += [
        "",
        "## Prototype thresholds (tunable after pilot testing)",
        "",
        "All SLS thresholds below are conservative starting values, not derived from pilot",
        "data, and should be revisited once real user sessions are available:",
        "",
        f"- `SLS_MAX_HOLD_SEC = {config.SLS_MAX_HOLD_SEC}` -- per-leg hold cap",
        f"- `SLS_LIFT_LINE_NORM = {config.SLS_LIFT_LINE_NORM}` -- lift-line height / stance-leg length",
        f"- `SLS_LIFT_HYSTERESIS_NORM = {config.SLS_LIFT_HYSTERESIS_NORM}` -- drop-confirmation margin",
        f"- `SLS_CIRCLE_RADIUS_NORM = {config.SLS_CIRCLE_RADIUS_NORM}` -- tolerance-circle radius / hip width",
        f"- `SLS_HOLD_WEIGHT / SLS_STABILITY_WEIGHT = {config.SLS_HOLD_WEIGHT} / {config.SLS_STABILITY_WEIGHT}` -- combined-score blend",
        f"- `SLS_HOLD_POOR_MAX_SEC / SLS_HOLD_FAIR_MAX_SEC = {config.SLS_HOLD_POOR_MAX_SEC} / {config.SLS_HOLD_FAIR_MAX_SEC}` -- Table 6 hold breakpoints",
        "",
        "## Monocular-depth limitation",
        "",
        "A single webcam cannot reliably measure depth (toward/away-from-camera) sway or true",
        "centre of mass. The stability sub-score therefore uses only the reliable **frontal-plane",
        "(left-right, x-axis)** hip-midpoint offset (`sls/geometry.py:ball_x_norm`) -- the z-axis",
        "is deliberately ignored for scoring. This is why hold time remains the **primary**",
        "measure and the stability sub-score is treated as a supporting indicator only, bounded",
        "by this single-camera limitation. State this explicitly in write-ups; it reads as rigour",
        "rather than an oversight.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run the SLS measurement-agreement evaluation"
    )
    parser.add_argument(
        "--report-out",
        default=str(DEFAULT_REPORT_PATH),
        help="Markdown report output path",
    )
    args = parser.parse_args()

    result = evaluate()
    print(
        f"[eval] n={result['n']} ICC(2,1)={result['icc_2_1']} kappa={result['cohens_kappa']}"
    )
    print(f"[eval] Bland-Altman: {result['bland_altman']}")

    report = render_report(result)
    out_path = Path(args.report_out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report)
    print(f"[eval] Wrote report to {out_path}")


if __name__ == "__main__":
    main()
