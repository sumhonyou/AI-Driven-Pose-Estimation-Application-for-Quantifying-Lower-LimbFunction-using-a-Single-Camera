def analyse(frames: list[dict]) -> dict:
    """Run the real router pipeline over one sample's frames (X1).

    Deliberately mirrors `router.py`'s exact order and semantics — quality on the raw
    buffer, preprocessing over the whole stream, then segment/extract/score/fuse —
    rather than re-deriving a convenient variant. This is what makes the measured band
    in `labels.json` the band the live endpoint would actually return.
    """
    quality = assess_capture_quality(frames)
    preprocessed = preprocess_world_landmarks(frames)
    reps = segment_squat_frames(preprocessed)
    if not reps:
        return {"n_reps": 0, "band": None, "error": "no reps segmented"}

    feature_vectors = [extract_squat_features(rep) for rep in reps]
    rule_scores = score_squat_set(reps and feature_vectors)
    if rule_scores.score is None:
        return {"n_reps": len(reps), "band": None, "error": "no rule score"}

    fusion = fuse_model(
        rule_scores=rule_scores,
        model=get_model_bundle("squat"),
        features=feature_vectors[0],
        q=float(quality["q"]),
    )
    return {
        "n_reps": len(reps),
        "band": fusion.band,
        "score": round(fusion.score, 4),
        "rule_score": round(rule_scores.score, 4),
        "confidence": round(fusion.confidence, 4),
        "q": round(float(quality["q"]), 4),
        "flags": list(fusion.flags),
        "peak_knee_flexion_deg": round(
            max(mean_knee_flexion_deg(f) for f in preprocessed), 2
        ),
    }


def _verify_construction(spec: dict, frames: list[dict]) -> None:
    """Check the built pose actually has the knee flexion the spec asked for.

    Read back through the real `mean_knee_flexion_deg()` (X1) on the RAW frames, so a
    bug in `_leg_points()`'s trigonometry fails loudly here instead of silently
    producing a corpus whose specs describe a movement it does not contain. Raw, not
    preprocessed: One Euro legitimately shifts the peak (see `_make_world`), so
    asserting on the smoothed signal would be asserting on the filter, not the geometry.
    """
    raw_peak = max(mean_knee_flexion_deg(frame) for frame in frames)
    # Tolerance covers only POSE_NOISE_M's effect on the angle; the profile itself
    # reaches the requested peak exactly.
    if abs(raw_peak - spec["peak_flexion_deg"]) > 1.0:
        raise AssertionError(
            f"{spec['sample_id']}: constructed pose peaks at {raw_peak:.2f} deg but the "
            f"spec asked for {spec['peak_flexion_deg']:.2f} deg — _leg_points() is not "
            "reproducing the requested angle."
        )


def build_corpus() -> list[dict]:
    rng = random.Random(SEED)
    manifest = []
    for spec in SAMPLE_SPECS:
        frames = _build_frames(spec, rng)
        _verify_construction(spec, frames)
        measured = analyse(frames)
        (CORPUS_DIR / f"{spec['sample_id']}.json").write_text(
            json.dumps(frames, separators=(",", ":"))
        )
        manifest.append(
            {
                "sample_id": spec["sample_id"],
                "frames_file": f"{spec['sample_id']}.json",
                "n_frames": len(frames),
                "target_band_hint": spec["target_band_hint"],
                # The band the real pipeline actually produced, measured at build
                # time. This is the field the tests assert against.
                "measured": measured,
                "hint_matched": measured["band"] == spec["target_band_hint"],
                "spec": {
                    key: spec[key]
                    for key in sorted(spec)
                    if key not in {"sample_id", "target_band_hint"}
                },
            }
        )
    return manifest


def main() -> None:
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    manifest = build_corpus()
    model_version = get_model_bundle("squat").model_version
    (CORPUS_DIR / "labels.json").write_text(
        json.dumps(
            {
                "generator": "ml/scripts/generate_squat_replay_corpus.py",
                "seed": SEED,
                "fps": FPS,
                "model": model_version,
                "config_at_build": {
                    key: MODULE_B_CORE_CONFIG[key]
                    for key in (
                        "w_rule_default",
                        "w_ml_default",
                        "confidence_low_threshold",
                        "q_min",
                        "feature_schema_version",
                    )
                },
                "note": (
                    "`measured` is what the real pipeline produced at build time, not "
                    "a hand-written expectation. Stage 5.8 swapped in the trained "
                    "model (`model_version` above): unlike the Phase 4 StubModel "
                    "placeholder, there is no closed-form rule mapping a rule_score to "
                    "a reachable band any more — the forest's decision boundary and its "
                    "calibration are learned, not analytic, so which band a given "
                    "synthetic sample lands in can only be discovered by running it "
                    "through the real pipeline, which is what this manifest records. "
                    "Regenerate this file after any retraining rather than editing it."
                ),
                "samples": manifest,
            },
            indent=2,
        )
        + "\n"
    )

    print(f"[corpus] Wrote {len(manifest)} samples + labels.json to {CORPUS_DIR}")
    for item in manifest:
        measured = item["measured"]
        flag = "OK " if item["hint_matched"] else "!! "
        print(
            f"  {flag}{item['sample_id']:28s} band={str(measured['band']):5s} "
            f"(hint {item['target_band_hint']:5s}) reps={measured['n_reps']} "
            f"rule={measured.get('rule_score')} q={measured.get('q')} "
            f"peak={measured.get('peak_knee_flexion_deg')}deg "
            f"flags={measured.get('flags')}"
        )
    mismatched = [item["sample_id"] for item in manifest if not item["hint_matched"]]
    if mismatched:
        print(f"\n[corpus] NOTE: measured band != hint for: {', '.join(mismatched)}")
        print(
            "[corpus] The manifest records the measured band; fix the spec or the hint."
        )


if __name__ == "__main__":
    main()
