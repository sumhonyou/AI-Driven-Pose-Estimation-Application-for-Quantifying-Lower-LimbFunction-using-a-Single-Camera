"""Generates the committed squat replay corpus (Stage 5.7, respecced under the real
model in Stage 5.8 — see point 2 below).

Synthetic side-view squat sets spanning every band the shipped model has been found to
actually reach (Good and Fair — **not Poor**; see point 2), plus a low-capture-quality
reject, committed to `backend/app/module_b/replay_corpus/squat/` so the determinism
tests and the replay harness run from fixed data without needing the REHAB24-6 dataset
(which lives outside the repo and cannot be committed).

Mirrors Module A's Stage 7 precedent (`generate_sls_replay_corpus.py`): fixed seed,
committed output, a `labels.json` manifest. Three things differ, each for a reason.

1. **The manifest records what each sample *actually* produced, not what it was
   designed to produce.** Module A's corpus stores a `target_band_hint`. Here every
   sample is run through the real pipeline at build time and the *measured* band, rule
   score and flags are written to `labels.json`. The intended band is kept alongside as
   `target_band_hint`, and `hint_matched` records whether they agree. A hand-written
   expectation that silently stops matching the code is exactly the kind of stale
   fixture this corpus exists to catch.

2. **Which band a sample reaches now depends on a trained, non-analytic model
   (Stage 5.8), and this corpus no longer includes a Poor sample — because none could
   be found, and that absence is itself a documented finding, not an oversight.**
   Before Stage 5.8, the Phase 4 `StubModel` placeholder derived
   `P(Good) = rule_score/10` exactly, so a sample's band could be predicted from its
   `rule_score` by a simple formula, and "deep + unstable" reliably read as Poor
   (rewarding depth is what the analytic rule score does). `get_model_bundle("squat")`
   replaced it with the real Extra Trees forest + sigmoid calibration, which learned
   the **opposite** relationship for this population — Stage 5.4/5.5/5.6 already
   established that incorrect repetitions in this dataset are *deeper*, not shallower —
   so the old "deep + unstable = Poor" specs now read as confidently *Good* or merely
   uncertain instead.

   Rebuilding the specs around the real model's actual (measured, not assumed) Good/Poor
   feature statistics and then sweeping depth, lean, tempo and sway against
   `get_model_bundle("squat")` directly, the lowest confidence toward Poor reached by
   any geometry tried — including implausibly extreme ones — was P(Good)≈0.50, well
   short of the ≤0.15 that `confidence_low_threshold=0.85` requires to band Poor. This
   matches a stronger, independently-measured fact: `export_squat_model.py`'s own
   `_deployed_confidence_check()` found that **the single most Poor-leaning row in the
   entire 98-repetition training set** only reaches P(Good)=0.244 — the shipped
   model never crosses the confidence bar toward Poor on its own training data, let
   alone on synthetic geometry it has never seen. Two closest-approach samples
   (`attempted_poor_deep_unstable_1`/`_2`) are kept to record this rather than silently
   dropped; their `target_band_hint` is honestly `"Fair"`.

   The corpus remains a **determinism fixture, not a correctness oracle** — it is not
   evidence the model is accurate on synthetic geometry, only that it is deterministic
   on it. `labels.json`'s `measured` block is regenerated by re-running this script,
   never hand-patched, exactly because no formula can predict it.

3. **Geometry is built from joint angles, forwards.** Rather than hand-placing
   landmarks and hoping the resulting angles land somewhere useful, each frame is
   constructed from a target knee flexion and shank tilt, so a spec says what it means.
   The build then verifies the constructed pose reproduces the requested angle through
   the *real* `mean_knee_flexion_deg()` (X1) rather than trusting the construction.

Deterministic (X8): seeded RNG, fixed specs, sorted iteration, no wall-clock.

Usage:
    python generate_squat_replay_corpus.py
"""

