FRAME_DT = 1.0 / FPS
STANDING_FLEXION_DEG = 5.0
STANDING_PAD_S = 0.6  # standing frames either side, so the FSM starts/ends in READY

# Segment lengths in metres, roughly adult proportions. Only their ratios matter.
SHANK_LEN = 0.42
THIGH_LEN = 0.42
TRUNK_LEN = 0.50
HALF_STANCE_Z = 0.09  # ankles at z = +-0.09 -> stance width 0.18 m

# Jitter noise is tiny and only exists so frames are not bit-identical; the
# *intended* instability in a spec comes from `sway_amplitude`, not from this.
POSE_NOISE_M = 0.001


def _r(value: float) -> float:
    """4dp is well beyond what these synthetic coordinates need; rounding keeps the
    committed JSON compact (default float repr bloats the file)."""
    return round(value, 4)


def _leg_points(
    flexion_deg: float, shank_tilt_deg: float, ankle_y: float
) -> tuple[tuple[float, float], tuple[float, float], tuple[float, float]]:
    """Build (ankle, knee, hip) in the sagittal x-y plane from joint angles.

    x is forward, y is *down* (MediaPipe world convention). The knee's interior angle
    is set to `180 - flexion_deg`, so `knee_flexion_deg()` reads back `flexion_deg`.
    Of the two possible hip placements, the higher one (smaller y) is the anatomical
    one — a squat bends the knee with the hip above it, not below.
    """
    ankle = (0.0, ankle_y)
    tilt = math.radians(shank_tilt_deg)
    knee = (
        ankle[0] + SHANK_LEN * math.sin(tilt),
        ankle[1] - SHANK_LEN * math.cos(tilt),
    )

    # Direction knee -> ankle, and the two candidate thigh directions at the required
    # interior angle from it.
    to_ankle = math.atan2(ankle[1] - knee[1], ankle[0] - knee[0])
    interior = math.radians(180.0 - flexion_deg)
    candidates = [
        (
            knee[0] + THIGH_LEN * math.cos(to_ankle + interior),
            knee[1] + THIGH_LEN * math.sin(to_ankle + interior),
        ),
        (
            knee[0] + THIGH_LEN * math.cos(to_ankle - interior),
            knee[1] + THIGH_LEN * math.sin(to_ankle - interior),
        ),
    ]
    hip = min(candidates, key=lambda point: point[1])
    return ankle, knee, hip


def _make_world(
    flexion_deg: float,
    shank_tilt_deg: float,
    trunk_lean_deg: float,
    sway_x: float,
    visibility: float,
    rng: random.Random,
) -> list[dict]:
    """One 33-landmark world pose. Only the indices Module B reads are meaningful.

    `sway_x` translates the whole body, so it perturbs `hip_mid_jitter_norm` (which
    measures hip travel) without touching any joint angle *in the raw pose*.

    It does not stay independent downstream, and that is worth knowing rather than
    assuming: One Euro's cutoff is speed-adaptive (`min_cutoff + beta * |velocity|`), so
    a large sway raises the x-velocity, widens the cutoff, and therefore smooths the
    landmark *less*. Measured on this corpus: raw peak knee flexion is identical
    (36.19 deg) at sway 0.0 and 0.4, but the preprocessed peak moves 35.44 -> 36.44 deg,
    which is enough to change how many reps segment. Whole-body translation is coupled
    to angle smoothing through the filter, not through the geometry.
    """
    ankle, knee, hip = _leg_points(flexion_deg, shank_tilt_deg, ankle_y=1.0)
    lean = math.radians(trunk_lean_deg)
    shoulder = (
        hip[0] + TRUNK_LEN * math.sin(lean),
        hip[1] - TRUNK_LEN * math.cos(lean),
    )

    def point(xy: tuple[float, float], z: float) -> dict:
        return {
            "x": _r(xy[0] + sway_x + rng.uniform(-POSE_NOISE_M, POSE_NOISE_M)),
            "y": _r(xy[1] + rng.uniform(-POSE_NOISE_M, POSE_NOISE_M)),
            "z": _r(z),
            "visibility": visibility,
        }

    zero = {"x": 0.0, "y": 0.0, "z": 0.0, "visibility": visibility}
    world = [dict(zero) for _ in range(33)]
    # Left/right are identical apart from their z offset: a true sagittal view cannot
    # distinguish them anyway (see the symmetry_index limitation in the reports), so
    # inventing an asymmetry here would fake a signal the geometry does not carry.
    for index, xy in ((11, shoulder), (23, hip), (25, knee), (27, ankle)):
        world[index] = point(xy, -HALF_STANCE_Z)
    for index, xy in ((12, shoulder), (24, hip), (26, knee), (28, ankle)):
        world[index] = point(xy, HALF_STANCE_Z)
    return world


def _flexion_profile(peak_deg: float, duration_s: float) -> list[float]:
    """One rep's knee-flexion trajectory: a raised cosine from standing to `peak_deg`.

    Smooth by construction, so the segmentation FSM sees a clean single-peak descent
    and ascent rather than threshold chatter — the corpus tests replay determinism, so
    a sample that segments ambiguously would be testing the wrong thing.
    """
    n_frames = max(int(round(duration_s * FPS)), 2)
    return [
        STANDING_FLEXION_DEG
        + (peak_deg - STANDING_FLEXION_DEG)
        * 0.5
        * (1.0 - math.cos(2.0 * math.pi * i / n_frames))
        for i in range(n_frames)
    ]


def _build_frames(spec: dict, rng: random.Random) -> list[dict]:
    """Assemble a whole set: standing pad, `n_reps` reps, standing pad."""
    flexions: list[float] = []
    pad = [STANDING_FLEXION_DEG] * int(round(STANDING_PAD_S * FPS))
    flexions.extend(pad)
    for rep_index in range(spec["n_reps"]):
        # Per-rep duration jitter drives tempo_consistency; a spec asking for an
        # inconsistent tempo gets genuinely uneven reps, not a hand-set feature value.
        duration = spec["rep_duration_s"] * (
            1.0 + spec["duration_variation"] * (rep_index - (spec["n_reps"] - 1) / 2.0)
        )
        flexions.extend(_flexion_profile(spec["peak_flexion_deg"], duration))
        flexions.extend([STANDING_FLEXION_DEG] * int(round(0.4 * FPS)))
    flexions.extend(pad)

    frames = []
    for i, flexion in enumerate(flexions):
        t = i * FRAME_DT
        progress = (flexion - STANDING_FLEXION_DEG) / max(
            spec["peak_flexion_deg"] - STANDING_FLEXION_DEG, 1e-9
        )
        # Shank tilt and trunk lean both grow with depth, as they do in a real squat.
        shank_tilt = spec["shank_tilt_deg"] * progress
        trunk_lean = spec["trunk_lean_deg"] * progress
        sway_x = spec["sway_amplitude"] * math.sin(2.0 * math.pi * spec["sway_hz"] * t)
        frames.append(
            {
                "timestampMs": round(t * 1000.0, 1),
                "worldLandmarks": _make_world(
                    flexion, shank_tilt, trunk_lean, sway_x, spec["visibility"], rng
                ),
            }
        )
    return frames


